
CREATE TABLE reported_income (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    taxpayer_id BIGINT NOT NULL
        REFERENCES taxpayer(id),

    reporting_source VARCHAR(100) NOT NULL,

    source_reference VARCHAR(100) NOT NULL,

    tax_year INTEGER NOT NULL,

    reported_income NUMERIC(19, 2) NOT NULL,

    received_at TIMESTAMP WITH TIME ZONE NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_reported_income_source_reference
        UNIQUE (reporting_source, source_reference),

    CONSTRAINT chk_reported_income_tax_year
        CHECK (tax_year >= 2000),

    CONSTRAINT chk_reported_income_amount
        CHECK (reported_income >= 0)
);

CREATE INDEX idx_reported_income_taxpayer_year
    ON reported_income (taxpayer_id, tax_year);
