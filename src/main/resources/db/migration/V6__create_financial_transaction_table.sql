
CREATE TABLE financial_transaction (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    transaction_id VARCHAR(100) NOT NULL,
    transaction_date DATE,
    customer_id VARCHAR(100),
    amount NUMERIC(19, 2),
    tax_rate NUMERIC(9, 6),
    reported_tax NUMERIC(19, 2),
    transaction_type VARCHAR(20),

    raw_transaction JSONB NOT NULL,

    validation_status VARCHAR(20) NOT NULL,
    failure_reasons JSONB,

    expected_tax NUMERIC(19, 2),
    tax_gap NUMERIC(19, 2),
    compliance_status VARCHAR(30),

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_financial_transaction_validation_status
        CHECK (validation_status IN ('SUCCESS', 'FAILURE')),

    CONSTRAINT chk_financial_transaction_type
        CHECK (
            transaction_type IS NULL
            OR transaction_type IN ('SALE', 'REFUND', 'EXPENSE')
        ),

    CONSTRAINT chk_financial_transaction_amount
    CHECK (
        validation_status = 'FAILURE'
        OR (amount IS NOT NULL AND amount > 0)
    ),

    CONSTRAINT chk_financial_transaction_tax_rate
        CHECK (tax_rate IS NULL OR tax_rate >= 0),

    CONSTRAINT chk_financial_transaction_reported_tax
        CHECK (reported_tax IS NULL OR reported_tax >= 0),

    CONSTRAINT chk_financial_transaction_compliance_status
        CHECK (
            compliance_status IS NULL
            OR compliance_status IN (
                'COMPLIANT',
                'UNDERPAID',
                'OVERPAID',
                'NON_COMPLIANT'
            )
        )
);

CREATE INDEX idx_financial_transaction_customer_id
    ON financial_transaction (customer_id);

CREATE INDEX idx_financial_transaction_validation_status
    ON financial_transaction (validation_status);

CREATE INDEX idx_financial_transaction_date
    ON financial_transaction (transaction_date);

CREATE INDEX idx_financial_transaction_compliance_status
    ON financial_transaction (compliance_status);
