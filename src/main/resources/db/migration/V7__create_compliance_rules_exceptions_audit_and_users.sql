CREATE TABLE compliance_rule (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rule_name VARCHAR(100) NOT NULL UNIQUE,
    rule_type VARCHAR(50) NOT NULL,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    severity VARCHAR(10) NOT NULL,
    configuration JSONB NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_compliance_rule_severity
        CHECK (severity IN ('HIGH', 'MEDIUM', 'LOW'))
);

CREATE TABLE compliance_exception (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_id VARCHAR(100) NOT NULL,
    customer_id VARCHAR(100),
    rule_name VARCHAR(100) NOT NULL,
    severity VARCHAR(10) NOT NULL,
    message TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_compliance_exception_severity
        CHECK (severity IN ('HIGH', 'MEDIUM', 'LOW'))
);
CREATE INDEX idx_compliance_exception_customer ON compliance_exception(customer_id);
CREATE INDEX idx_compliance_exception_severity ON compliance_exception(severity);
CREATE INDEX idx_compliance_exception_rule ON compliance_exception(rule_name);
CREATE INDEX idx_compliance_exception_created_at ON compliance_exception(created_at);

CREATE TABLE audit_event (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_id VARCHAR(100) NOT NULL,
    event_type VARCHAR(30) NOT NULL,
    event_timestamp TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    detail_json JSONB NOT NULL,
    CONSTRAINT chk_audit_event_type
        CHECK (event_type IN ('INGESTION', 'RULE_EXECUTION', 'TAX_COMPUTATION'))
);
CREATE INDEX idx_audit_event_transaction ON audit_event(transaction_id);
CREATE INDEX idx_audit_event_type_timestamp ON audit_event(event_type, event_timestamp);

CREATE TABLE app_user (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(100) NOT NULL UNIQUE,
    password_hash VARCHAR(200) NOT NULL,
    role VARCHAR(30) NOT NULL DEFAULT 'USER',
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

