CREATE OR REPLACE FUNCTION set_compliance_rule_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_compliance_rule_updated_at
BEFORE UPDATE ON compliance_rule
FOR EACH ROW EXECUTE FUNCTION set_compliance_rule_updated_at();
