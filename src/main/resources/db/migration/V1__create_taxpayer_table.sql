CREATE TABLE taxpayer (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    taxpayer_reference VARCHAR(50) NOT NULL UNIQUE,
    legal_name VARCHAR(200) NOT NULL,
    tax_identifier VARCHAR(50) NOT NULL UNIQUE,
    tax_year INTEGER NOT NULL,
    declared_income NUMERIC(19, 2) NOT NULL,
    declared_tax NUMERIC(19, 2) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
        DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_taxpayer_tax_year
        CHECK (tax_year >= 2000),
    CONSTRAINT chk_taxpayer_declared_income
        CHECK (declared_income >= 0),
    CONSTRAINT chk_taxpayer_declared_tax
        CHECK (declared_tax >= 0)
);