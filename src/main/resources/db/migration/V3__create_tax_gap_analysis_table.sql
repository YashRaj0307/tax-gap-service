CREATE TABLE tax_gap_analysis (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    taxpayer_id BIGINT NOT NULL
        REFERENCES taxpayer(id),

    tax_year INTEGER NOT NULL,

    declared_income NUMERIC(19, 2) NOT NULL,
    reported_income NUMERIC(19, 2) NOT NULL,
    income_discrepancy NUMERIC(19, 2) NOT NULL,
    discrepancy_percentage NUMERIC(9, 4) NOT NULL,

    analysis_status VARCHAR(30) NOT NULL,
    analysis_reason TEXT NOT NULL,

    analyzed_at TIMESTAMP WITH TIME ZONE NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_analysis_tax_year
        CHECK (tax_year >= 2000),

    CONSTRAINT chk_analysis_declared_income
        CHECK (declared_income >= 0),

    CONSTRAINT chk_analysis_reported_income
        CHECK (reported_income >= 0),

    CONSTRAINT chk_analysis_percentage
        CHECK (discrepancy_percentage >= 0),

    CONSTRAINT chk_analysis_status
        CHECK (analysis_status IN ('NO_DISCREPANCY', 'REVIEW_REQUIRED'))
);

CREATE INDEX idx_tax_gap_analysis_taxpayer_year
    ON tax_gap_analysis (taxpayer_id, tax_year);